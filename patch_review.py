import re, sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
D = 'hard/'

def read(g): return open(D + g + '.txt', encoding='utf-8').read()
def write(g, s): open(D + g + '.txt', 'w', encoding='utf-8').write(s)

def set_unit(g, n, body):
    s = read(g)
    parts = re.split(r'(?m)^## (\d+)\n', s)
    # parts: ['', '1', body1, '2', body2, ...]
    out = [parts[0]]
    found = False
    for i in range(1, len(parts), 2):
        out.append(f'## {parts[i]}\n')
        if int(parts[i]) == n:
            out.append(body.strip('\n') + '\n'); found = True
        else:
            out.append(parts[i + 1])
    assert found, (g, n)
    write(g, ''.join(out))

def set_line(g, stem, new):
    """用題幹開頭片段（|之後的第一段）定位並整行取代。"""
    lines = read(g).split('\n')
    hit = [i for i, l in enumerate(lines) if len(l.split('|')) > 1 and l.split('|')[1].startswith(stem)]
    assert len(hit) == 1, (g, stem, hit)
    lines[hit[0]] = new
    write(g, '\n'.join(lines))

